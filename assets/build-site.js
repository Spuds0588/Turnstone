#!/usr/bin/env node
/* Turnstone — site artifacts and the link checks that keep them honest.
 *
 *   node assets/build-site.js            # write sitemap.xml and robots.txt, then verify
 *   node assets/build-site.js --check    # fail if either is out of date; write nothing
 *
 * Why this is generated rather than typed: a sitemap is a list of pages, and a list
 * of pages kept by hand is missing the newest page the day after somebody adds it.
 * So the page list comes from the directory itself, and adding a page is all it
 * takes to have it appear.
 *
 * The same script is also where the **agent-facing** link graph is checked, because
 * that graph is the part nobody looks at in a browser: an `llms.txt` pointing at a
 * file that was renamed, or a `rel="alternate"` markdown twin that was never written,
 * fails silently for a person and completely for a machine. Everything here is a
 * filesystem fact, so all of it can be asserted rather than hoped for.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CHECK = process.argv.slice(2).includes('--check');
const SITE = 'https://spuds0588.github.io/Turnstone/';

/* Pages that live in the repository but are not pages of the site. Each one is
   excluded for a reason, and a reason is the price of being on this list. */
const NOT_A_PAGE = {
  'sample-links.html': 'a fixture — the HTML table the app is tested against, not a page',
  '404.html': 'not a page: only served for misses',
};

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const exists = (rel) => fs.existsSync(path.join(ROOT, rel));
const htmlFiles = () => fs.readdirSync(ROOT).filter((f) => f.endsWith('.html') && !f.startsWith('.'));

/** Every page of the site, in a deliberate order: the front door first, then the
    guides, then the app itself. Weight is how likely each is to be what someone
    searching wants to land on. */
function pages() {
  const weight = {
    'index.html': 1.0,
    'workspace-link.html': 0.9,
    'versions.html': 0.8,
    'web-app.html': 0.8,
    'standalone.html': 0.7,
    'bookmarklet.html': 0.7,
    'extension.html': 0.7,
    'app.html': 0.9,
    'turnstone-standalone.html': 0.4,
  };
  return htmlFiles()
    .filter((f) => !NOT_A_PAGE[f])
    .sort((a, b) => (weight[b] || 0.5) - (weight[a] || 0.5) || a.localeCompare(b))
    /* The root page's canonical is the directory, not `index.html` — that is what the
       page already declared, and it is the URL people actually share. */
    .map((f) => ({ file: f, url: f === 'index.html' ? SITE : SITE + f, priority: weight[f] || 0.5 }));
}

/* ---------------------------------------------------------------- writers --- */

function sitemap() {
  const list = pages();
  const body = list.map((p) => `  <url>\n    <loc>${p.url}</loc>\n    <priority>${p.priority.toFixed(1)}</priority>\n  </url>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n`
    + `<!-- Generated by assets/build-site.js — do not hand-edit.\n`
    + `     No <lastmod>: the only timestamps available here are file mtimes, which change\n`
    + `     on every build and would make this file churn without meaning anything. A\n`
    + `     sitemap that changes on every build teaches crawlers to ignore it. -->\n`
    + `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
}

function robots() {
  /* The AI crawlers are named rather than left to `User-agent: *`. For a site that
     wants to be *understood* by answer engines — and whose whole agent story is a
     documented URL format — an explicit allow is the signal, and naming the major
     ones costs nothing. They are also the names people check for. */
  const ai = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-User', 'anthropic-ai', 'PerplexityBot', 'Google-Extended', 'Applebot-Extended', 'CCBot', 'cohere-ai', 'Meta-ExternalAgent', 'Bytespider'];
  return [
    '# Turnstone — everything here is meant to be read, by people and by agents.',
    '#',
    '#   /llms.txt                          the map, for language models',
    '#   /index.html.md                     Markdown versions of the pages',
    '#   /workspace-link.html.md            the list-in-a-URL format, in full',
    '',
    'User-agent: *',
    'Allow: /',
    '',
    ...ai.flatMap((bot) => [`User-agent: ${bot}`, 'Allow: /', '']),
    `Sitemap: ${SITE}sitemap.xml`,
    '',
  ].join('\n');
}

/* ------------------------------------------------------------- the checks --- */

/* ------------------------------------------------- what a page actually says --- */

/* The sales page is the one page where every sentence has to earn its place, so it
   gets a budget rather than an opinion. Raising the number is always an option —
   that is exactly why the check says "cut something" instead of handing over a
   constant that looks like a target. */
const LANDING_PROSE_BUDGET = 1000;

const NAMED_ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', hellip: '…', mdash: '—', ndash: '–', times: '×', middot: '·' };

/** One sentence, as text: entities decoded, curly quotes straightened, whitespace
    collapsed. Note what this does *not* do — strip tags. A marked-up answer may
    legitimately contain a literal `<payload>`, and every "remove the tags" regex
    there is would eat it. */
function plainText(s) {
  return String(s)
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => (NAMED_ENTITIES[n] !== undefined ? NAMED_ENTITIES[n] : m))
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\s\u00a0]+/g, ' ')
    .trim();
}

const stripMarkup = (html) => String(html)
  .replace(/<script[\s\S]*?<\/script>/gi, ' ')
  .replace(/<style[\s\S]*?<\/style>/gi, ' ')
  .replace(/<[^>]*>/g, ' ');

/** What a reader — or a crawler — actually sees. */
const visibleText = (html) => plainText(stripMarkup(html));

/** A sentence is wrapped one way in HTML — across lines, with a `<code>` tag in the
    middle of it — and another way in JSON, so the two sides are compared with the
    whitespace removed. Punctuation is still compared exactly, which is the part that
    matters: rewriting a sentence in the prose and not in the markup is the failure
    mode this guards, and it is invisible in a browser. */
const squeeze = (html) => visibleText(html).replace(/\s+/g, '');          // page side
const squeezeValue = (text) => plainText(text).replace(/\s+/g, '');       // JSON side

/** Every node of a parsed JSON-LD document whose @type is one of `types`. */
function nodesOfType(value, types, out = []) {
  if (Array.isArray(value)) { for (const v of value) nodesOfType(v, types, out); }
  else if (value && typeof value === 'object') {
    if (typeof value['@type'] === 'string' && types.includes(value['@type'])) out.push(value);
    for (const v of Object.values(value)) nodesOfType(v, types, out);
  }
  return out;
}

/** Same-site absolute URL → a path in this working tree, or null when it points
    somewhere that is not this site (GitHub, say). Fragments and queries dropped. */
function localPathFor(url) {
  const clean = String(url).split('#')[0].split('?')[0];
  if (!clean.startsWith(SITE)) return null;
  const rel = clean.slice(SITE.length);
  return rel === '' ? 'index.html' : rel;
}

function check() {
  const problems = [];
  const list = pages();

  /* 1. The sitemap and the directory agree, in both directions. */
  const inSitemap = new Set((read('sitemap.xml').match(/<loc>([^<]+)<\/loc>/g) || [])
    .map((m) => m.replace(/<\/?loc>/g, '')).map(localPathFor).filter(Boolean));
  for (const p of list) if (!inSitemap.has(p.file)) problems.push(`sitemap.xml is missing ${p.file}`);
  for (const f of inSitemap) if (!exists(f)) problems.push(`sitemap.xml lists ${f}, which does not exist`);
  for (const f of htmlFiles()) {
    if (NOT_A_PAGE[f]) continue;
    if (!inSitemap.has(f)) problems.push(`${f} exists but is not in sitemap.xml`);
  }

  /* 2. Every page's own metadata points at itself, and at real files. */
  for (const p of list) {
    const html = read(p.file);
    const canonical = (html.match(/<link rel="canonical" href="([^"]+)"/) || [])[1];
    if (!canonical) problems.push(`${p.file} has no canonical link`);
    else if (canonical !== p.url) problems.push(`${p.file} canonical is ${canonical}, expected ${p.url}`);

    const desc = (html.match(/<meta name="description" content="([^"]*)"/) || [])[1];
    if (!desc || desc.length < 40) problems.push(`${p.file} has no usable meta description`);
    if (desc && desc.length > 320) problems.push(`${p.file} meta description is ${desc.length} chars — search engines truncate near 160`);

    /* The markdown twin and the llms.txt pointer, if this page claims one. Each is
       resolved against the filesystem, which is the whole point: a twin that was
       never written is a dead end an agent walks into and a person never sees. */
    const alt = (html.match(/<link rel="alternate"[^>]*type="text\/markdown"[^>]*href="([^"]+)"/) || [])[1];
    if (alt && !exists(localPathFor(new URL(alt, p.url).href) || alt)) {
      problems.push(`${p.file} advertises the markdown twin ${alt}, which does not exist`);
    }
    const described = (html.match(/<link rel="describedby"[^>]*href="([^"]+)"/) || [])[1];
    if (described && !exists(localPathFor(new URL(described, p.url).href) || described)) {
      problems.push(`${p.file} points describedby at ${described}, which does not exist`);
    }

    /* Social images are the quietest thing on a page to get wrong: nobody browsing
       the site ever loads one, so a renamed or never-generated card file shows up
       only as a link that renders as text in somebody else's chat app. */
    for (const prop of ['og:image', 'twitter:image']) {
      const m = html.match(new RegExp(`<meta (?:property|name)="${prop}" content="([^"]+)"`));
      if (!m) continue;
      const rel = localPathFor(m[1]);
      if (rel && !exists(rel)) problems.push(`${p.file} advertises ${prop} ${m[1]}, which does not exist`);
    }

    /* Structured data is silently ignored when it does not parse, so a stray comma
       costs a page its rich result with no symptom anywhere. Every block is read. */
    const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
    if (!blocks.length) problems.push(`${p.file} carries no structured data at all`);
    const parsed = [];
    for (const [n, b] of blocks.entries()) {
      try {
        const data = JSON.parse(b[1]);
        if (!data['@context'] || !data['@type']) problems.push(`${p.file} ld+json block ${n + 1} has no @context/@type`);
        parsed.push(data);
      } catch (e) {
        problems.push(`${p.file} ld+json block ${n + 1} is not valid JSON: ${e.message}`);
      }
    }

    /* …and it has to describe the page it is on. Answer engines and Google both ask
       for markup that says what the page says, and nothing renders JSON-LD, so a
       page whose prose was rewritten while its markup was not looks perfect in a
       browser and is wrong to every machine that reads it. This is also, always,
       the moment a page like this grows a second copy of the same sentences. */
    const pageText = squeeze(html);   // tags gone: this is the page's own words
    /* Questions appear two ways on this site: `<summary>` inside a `<details>` on the
       landing page, and a `<dt>` in a definition list on the guide pages. Both are
       read, so the check works the same whichever one a page is written in. */
    const asked = [
      ...html.matchAll(/<summary[^>]*>([\s\S]*?)<\/summary>/g),
      ...html.matchAll(/<dt[^>]*>([\s\S]*?)<\/dt>/g),
    ].map((m) => m[1]);
    const questions = parsed.flatMap((d) => nodesOfType(d, ['Question']));
    const steps = parsed.flatMap((d) => nodesOfType(d, ['HowToStep']));
    for (const q of questions) {
      const name = visibleText(q.name || '');
      if (asked.length && !asked.some((s) => squeeze(s) === squeezeValue(name))) {
        problems.push(`${p.file}: the FAQ markup asks "${name}", which no question on the page asks`);
      }
      const answer = squeezeValue(q.acceptedAnswer && q.acceptedAnswer.text || '');
      if (answer && !pageText.includes(answer)) {
        problems.push(`${p.file}: the marked-up answer to "${name}" is not on the page — the prose and the JSON have drifted apart`);
      }
    }
    for (const s of asked) {
      if (!questions.some((q) => squeezeValue(q.name) === squeeze(s))) {
        problems.push(`${p.file}: "${visibleText(s)}" is asked on the page but missing from the FAQ markup`);
      }
    }
    for (const st of steps) {
      const text = squeezeValue(st.text || '');
      if (text && !pageText.includes(text)) {
        problems.push(`${p.file}: the marked-up HowTo step "${visibleText(st.name || '')}" does not say what the page says`);
      }
      const name = squeezeValue(st.name || '');
      if (name && !pageText.includes(name)) {
        problems.push(`${p.file}: the HowTo step "${visibleText(st.name || '')}" has no heading on the page`);
      }
    }

    /* The top bar is three items on purpose — Home, All versions, Launch app. The four
       editions are reached by the path the landing page sets up, and by every page's
       footer for anyone who would rather not walk it. Asserted because a bar that lists
       every page of a site is not navigation but a table of contents, and it grows back
       one "useful link" at a time. */
    const nav = (html.match(/<nav class="topnav"[\s\S]*?<\/nav>/) || [])[0];
    if (nav) {
      const hrefs = [...nav.matchAll(/<a class="(?:link|go)"[^>]*href="([^"]+)"/g)].map((m) => m[1]);
      if (hrefs.join(' ') !== 'index.html versions.html app.html') {
        problems.push(`${p.file}: the top bar is ${hrefs.join(' · ') || 'empty'} — it should be Home, All versions, Launch app`);
      }
    }
  }

  /* 3. The numbers the guide pages print with JavaScript switched off. site.js rewrites
       them from assets/sizes.json at runtime, which is exactly why the fallback text is
       the copy that goes stale unnoticed: it is what a reader with no scripts — and most
       crawlers — actually sees. These ages drifted a whole release behind before anybody
       looked, so they are compared to the artifacts now. */
  const sizes = JSON.parse(read('assets/sizes.json'));
  const sizeText = (n) => (n >= 1048576 ? (n / 1048576).toFixed(2) + ' MB' : Math.round(n / 1024) + ' KB');   // must match site.js
  for (const p of list) {
    const html = read(p.file);
    for (const m of html.matchAll(/<[^>]*\bdata-size-of="[^"]*"[^>]*>/g)) {
      const key = (m[0].match(/data-size-of="([^"]+)"/) || [])[1];
      const shown = (m[0].match(/data-size-fallback="([^"]+)"/) || [])[1];
      if (!shown) { problems.push(`${p.file} prints a size for ${key} with no fallback text — it reads blank without JavaScript`); continue; }
      const bytes = sizes[key];
      if (!bytes) problems.push(`${p.file} quotes a size for ${key}, which no build records`);
      else if (sizeText(bytes) !== shown) problems.push(`${p.file} says ${shown} for ${key}; the artifact is ${sizeText(bytes)}`);
    }
    for (const m of html.matchAll(/<[^>]*\bdata-(count|version)-of="[^"]*"[^>]*>/g)) {
      const kind = m[1];
      const key = (m[0].match(new RegExp(`data-${kind}-of="([^"]+)"`)) || [])[1];
      const shown = (m[0].match(new RegExp(`data-${kind}-fallback="([^"]+)"`)) || [])[1];
      if (!shown) { problems.push(`${p.file} prints a ${kind} for ${key} with no fallback text`); continue; }
      if (!exists(key)) { problems.push(`${p.file} quotes a ${kind} from ${key}, which does not exist`); continue; }
      let meta; try { meta = JSON.parse(read(key)); } catch { problems.push(`${p.file} reads a ${kind} from ${key}, which is not JSON`); continue; }
      const want = kind === 'version' ? 'v' + meta.version : String(meta.files);
      if (want !== shown) problems.push(`${p.file} says ${shown} for ${key}; the build says ${want}`);
    }
  }

  /* 4. The landing page's budget. A sales page grows one honest sentence at a time
       and ends up unreadable; the number is checked here so that trimming it is a
       build step rather than an intention. */
  const landingWords = visibleText(read('index.html')).split(' ').filter(Boolean).length;
  if (landingWords > LANDING_PROSE_BUDGET) {
    problems.push(`index.html has ${landingWords} words of visible prose; the budget is ${LANDING_PROSE_BUDGET} — cut something rather than raising this`);
  }

  /* 5. Every link in llms.txt resolves — including the ones into the repository,
       which are fetched by agents that will never open the site at all. */
  const llms = read('llms.txt');
  const links = [...llms.matchAll(/\]\((https?:[^)\s]+)\)/g)].map((m) => m[1]);
  if (!links.length) problems.push('llms.txt contains no links at all');
  for (const url of links) {
    if (url.startsWith('https://github.com/')) continue;      // repository links, not site files
    const rel = localPathFor(url);
    if (rel && !exists(rel)) problems.push(`llms.txt links to ${url}, which does not exist here`);
  }
  /* The spec's shape, because a malformed llms.txt is worse than none: an agent
     that cannot parse it gets nothing. H1, a blockquote summary, then file lists. */
  if (!/^# .+/m.test(llms)) problems.push('llms.txt has no H1 (the only required section)');
  if (!/^> .+/m.test(llms)) problems.push('llms.txt has no blockquote summary');
  const sections = llms.split(/^## /m).slice(1).map((s) => s.split('\n')[0].trim());
  const fileLists = llms.split(/^## /m).slice(1).filter((s) => /^- \[/m.test(s));
  if (!fileLists.length) problems.push('llms.txt has no H2 section holding a markdown list of links');

  /* 6. robots.txt allows this to be read at all, and points at the sitemap. */
  const r = read('robots.txt');
  if (!/^User-agent: \*/m.test(r)) problems.push('robots.txt has no default User-agent block');
  if (/^Disallow: \/$/m.test(r)) problems.push('robots.txt disallows everything — that cannot be intended');
  if (!r.includes(`Sitemap: ${SITE}sitemap.xml`)) problems.push('robots.txt does not point at the sitemap');
  for (const bot of ['GPTBot', 'ClaudeBot', 'PerplexityBot']) {
    if (!r.includes(`User-agent: ${bot}`)) problems.push(`robots.txt does not name ${bot}`);
  }

  return { problems, pages: list, linkCount: links.length, sections, landingWords, LANDING_PROSE_BUDGET };
}

/* ------------------------------------------------------------------ main --- */

function main() {
  const want = { 'sitemap.xml': sitemap(), 'robots.txt': robots() };
  const changed = [];
  for (const [file, content] of Object.entries(want)) {
    const current = exists(file) ? read(file) : null;
    if (current !== content) changed.push(file);
  }
  if (CHECK) {
    const { problems } = check();
    console.log(`\n  ${changed.length ? 'STALE: ' + changed.join(', ') : 'sitemap.xml and robots.txt are up to date'}`);
    if (problems.length) {
      console.log(`\n  ${problems.length} link problem(s):`);
      for (const p of problems) console.log(`    ! ${p}`);
    } else {
      console.log('  every agent-facing link resolves');
    }
    process.exit(changed.length || problems.length ? 1 : 0);
  }
  for (const [file, content] of Object.entries(want)) fs.writeFileSync(path.join(ROOT, file), content);

  const { problems, pages: list, linkCount, sections, landingWords } = check();
  console.log('Turnstone — site artifacts');
  console.log(`  pages           ${list.length}${changed.length ? ` (${changed.join(', ')} rewritten)` : ''}`);
  console.log(`  llms.txt        ${linkCount} links, ${sections.length} sections: ${sections.join(' · ')}`);
  console.log(`  landing prose   ${landingWords} of ${LANDING_PROSE_BUDGET} words`);
  if (problems.length) {
    console.log(`\n  ${problems.length} problem(s) — these are not warnings:`);
    for (const p of problems) console.log(`    ! ${p}`);
    process.exit(1);
  }
  console.log('  link checks     every agent-facing link resolves');
}

/* Guarded on `require.main` so test/run.js can import `pages()` and `check()` and
   assert the same things this script does, rather than keeping a second copy of what
   counts as a page — which is how the fixture page nearly became a canonical-tag
   failure in the suite. */
if (require.main === module) main();

module.exports = { pages, check, NOT_A_PAGE, SITE, localPathFor, visibleText, plainText, LANDING_PROSE_BUDGET };
